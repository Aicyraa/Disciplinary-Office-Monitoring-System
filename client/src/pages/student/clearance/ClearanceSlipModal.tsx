import { createPortal } from 'react-dom';
import type { ClearanceSlipView } from '@shared/types';
import { FormModal } from '@/components/feedback';
import { PageError, Spinner } from '@/components/feedback/PageState';
import { Button } from '@/components/ui/Button';
import { Icon } from '@/components/ui/Icon';
import { api } from '@/api/client';
import { useApi } from '@/hooks/useApi';
import { formatDate, formatTerm } from '@/utils/format';

function SlipDocument({ slip }: { slip: ClearanceSlipView }) {
  const name = `${slip.student.firstName} ${slip.student.lastName}`;
  return (
    <article aria-label="Clearance slip" className="rounded-xl border border-line bg-white p-6 print:max-w-none print:rounded-none print:border-0 print:p-0">
      <header className="border-b border-line pb-4 text-center">
        <p className="text-xs font-semibold tracking-widest text-muted uppercase">NU Fairview</p>
        <h2 className="text-xl font-bold text-ink">Student Discipline Office</h2>
        <p className="mt-1 text-lg font-semibold text-ink">Clearance slip</p>
        <p className="text-sm text-muted">{formatTerm(slip.academicYear, slip.semester)}</p>
      </header>
      <dl className="mt-4 grid grid-cols-[7rem_1fr] gap-y-2 text-sm">
        <dt className="text-muted">Name</dt>
        <dd className="font-medium text-ink">{name}</dd>
        <dt className="text-muted">Student ID</dt>
        <dd className="font-medium text-ink">{slip.student.studentId}</dd>
        <dt className="text-muted">Program</dt>
        <dd className="text-ink">{slip.student.program}</dd>
        <dt className="text-muted">Cleared on</dt>
        <dd className="text-ink">{slip.clearedOn ? formatDate(slip.clearedOn) : '—'}</dd>
      </dl>
      <h3 className="mt-6 text-xs font-semibold tracking-wide text-muted uppercase">Requirements</h3>
      <ul className="mt-2 divide-y divide-line border-y border-line">
        {slip.items.map((item) => (
          <li key={item.label} className="flex items-center justify-between gap-3 py-2 text-sm">
            <span className="text-ink">{item.label}</span>
            <span className="text-muted">{item.dateCompleted ? `Completed ${formatDate(item.dateCompleted)}` : 'Completed'}</span>
          </li>
        ))}
      </ul>
      <p className="mt-6 flex items-center justify-center gap-1.5 text-sm font-bold tracking-wide text-success">
        <Icon name="verified" filled className="!text-xl" />
        CLEARED
      </p>
      <p className="mt-5 text-xs text-muted">This slip is generated by the SDO Portal. Present it at the SDO office when asked.</p>
    </article>
  );
}

/**
 * The clearance slip as a dialog over the Clearance page. "Print or save as PDF" prints a copy of the slip
 * that is rendered straight under the body (see the print rules in index.css), so the dialog frame never prints.
 * The API refuses the slip until every requirement is done.
 */
export function ClearanceSlipModal({ academicYear, semester, onClose }: { academicYear: number; semester: number; onClose: () => void }) {
  const slip = useApi(() => api.myClearanceSlip(academicYear, semester), [academicYear, semester]);
  const ready = slip.status === 'ready';
  return (
    <>
      <FormModal
        open
        icon="verified"
        title="Clearance slip"
        subtitle={formatTerm(academicYear, semester)}
        onClose={onClose}
        maxWidth="max-w-[600px]"
        footer={
          <>
            <Button variant="neutral" size="lg" onClick={onClose}>
              Close
            </Button>
            <Button size="lg" disabled={!ready} onClick={() => window.print()}>
              <Icon name="print" className="!text-xl" />
              Print or save as PDF
            </Button>
          </>
        }
      >
        {slip.status === 'loading' ? (
          <p role="status" className="flex items-center justify-center gap-2 py-10 text-[13px] text-muted">
            <Spinner />
            Preparing your slip…
          </p>
        ) : null}
        {slip.status === 'error' ? <PageError page="your clearance slip" detail={slip.error.message} onRetry={slip.reload} /> : null}
        {slip.status === 'ready' ? <SlipDocument slip={slip.data.slip} /> : null}
      </FormModal>
      {slip.status === 'ready'
        ? createPortal(
            <div className="print-slip-root hidden print:block">
              <SlipDocument slip={slip.data.slip} />
            </div>,
            document.body,
          )
        : null}
    </>
  );
}
